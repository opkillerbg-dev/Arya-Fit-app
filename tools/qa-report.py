#!/usr/bin/env python3
"""Writes docs/onboarding/08_QA_CHECKLIST.md from docs/onboarding/exercises.seed.json (tables for the S10 reviewer). Run from the repo root."""
import json
ex = json.load(open("docs/onboarding/exercises.seed.json", encoding="utf-8"))["ex"]
groups = {}
for e in ex: groups.setdefault(e["g"], []).append(e)
order = ["pushup", "bench", "dip", "vpush", "pullup", "row", "pullacc", "squat", "single", "squatx", "hinge", "calf", "core", "cardio", "mobility"]
nb = sum(1 for e in ex if not e["b"])
o = []
o.append("# S10 content QA: reviewer checklist\n")
o.append("Generated by `python3 tools/qa-report.py` from `exercises.seed.json` (the file to edit; then run `python3 tools/build-exdb.py`). "
         "Rules that a computer can check are tested in `tests/exdb.test.js` and `tests/plangen.test.js`; everything else needs a person.\n")
o.append("## What was checked automatically\n")
for t in ["Every exercise has a one-sentence cue (20-118 characters, ends with a full stop) and default reps (max 20 characters).",
          "No cue contains medical claims (cure, treat, diagnose, therapy, heal, rehab, prevent injury, guarantee).",
          "Equipment tags and body-area tags come from a fixed list; gym-only tags (dip station, low bar, barbell, machine, cable) never reach a home plan.",
          "Every ladder has no gaps between steps; levels are 0 to 5.",
          "A person with no equipment and any mix of protected areas (knee, back, shoulder, wrist, elbow) still gets push, pull, squat, hinge and core exercises.",
          "500 random profiles build plans that pass the app's real plan validator, respect equipment and protected areas, keep pull sets at 0.8 x push sets or more and stay inside the session set budget."]:
    o.append("- [x] " + t)
o.append("\n## Changes made in this QA pass\n")
for t in ["Squat jumps level 3 -> 2 and Nordic curl negatives level 5 -> 4 (S1) so ladders have no gaps.",
          "Parallel bar dips and weighted dips now need a dip station (`dipbar`): a doorway pull-up bar cannot do them. Home plans no longer get them.",
          "Inverted rows and feet-elevated inverted rows now need a low bar (`lowbar`): a doorway pull-up bar is too high. Home pulling uses table rows, backpack rows and dumbbell rows instead.",
          "Incline push-ups and knee push-ups now also protect wrists. Couch stretch protects knees; band shoulder dislocates and doorway chest stretch protect shoulders.",
          "At a gym, plans prefer dumbbell, barbell, machine and cable exercises over backpack and chair versions.",
          "Cues and default reps written for all %d exercises. Built-in exercises (those with pictures) keep their existing notes and reps." % len(ex)]:
    o.append("- " + t)
o.append("\n## Reviewer checklist (needs a person)\n")
for t in ["Levels: within each ladder below, is every step clearly harder than the one before? (Level 1 = beginner can just do it, 5 = very advanced.)",
          "Equipment: does each exercise list only what is really needed? (`body` = nothing, `chair` = a sturdy chair or table.)",
          "Protect tags: if a person protects that body area, is it right to leave this exercise out? Too many tags removes useful options, too few is unsafe.",
          "Cues: is each sentence correct, safe and understandable for a beginner? Any wording that could read as medical advice?",
          "Reps: are the default reps sensible for the level? (Holds are in seconds, one-sided moves say 'per side'.)",
          "Copy: read the screens in the app once, start to end, as a new user (health question, gentle-mode and under-18 notes, plan notes, retest results).",
          "Pictures: %d exercises have no picture yet (marked below). Decide which to illustrate first." % nb]:
    o.append("- [ ] " + t)
o.append("\nSigned off by: ______________________   Date: ______________\n")
o.append("## Copy that touches safety (read these in the app)\n")
for t in ["Health screen: \"Has a doctor ever said you should not exercise, or do you get chest pain or dizziness when you do?\" and, for Yes or Not sure, \"Please check with a doctor before you start. We will begin in gentle mode: fewer sets, longer rests and no max-effort tests. This is not medical advice.\"",
          "Skipping the health screen means gentle mode.",
          "Under 18: \"we will keep it gentle, with no max-effort tests\" and no weighted or max-effort work, at most 12 sets per session.",
          "Plan notes: \"Week 1 is a test week: start one level lower, stop 2 reps before failure and log your reps.\" and \"If something hurts, stop and see a doctor. This is not medical advice.\"",
          "Protected areas: \"Exercises that load your knee were left out.\" (the app never promises this fixes a problem).",
          "Gym loads: \"Start about X kg\" is 60% of the best weight the person typed in; \"Find a weight you can do 10 reps with, 2 left in the tank.\""]:
    o.append("- " + t)
o.append("\n## Exercises by ladder\n")
o.append("Columns: L = level step, Needs = equipment tags, Protects = body areas that remove it, Pic = has a picture in the app.\n")
for g in order:
    if g not in groups: continue
    o.append("### %s (%s)\n" % (g, groups[g][0]["p"]))
    o.append("| L | Exercise | Needs | Protects | Reps | Pic | Cue |")
    o.append("|---|---|---|---|---|---|---|")
    for e in sorted(groups[g], key=lambda x: (x["L"], x["id"])):
        o.append("| %d | %s | %s | %s | %s | %s | %s |" % (e["L"], e["n"], ", ".join(e["e"]), ", ".join(e["av"]) or "-", e["reps"], "yes" if e["b"] else "no", e["cue"]))
    o.append("")
open("docs/onboarding/08_QA_CHECKLIST.md", "w", encoding="utf-8").write("\n".join(o) + "\n")
print("wrote docs/onboarding/08_QA_CHECKLIST.md,", len(ex), "exercises,", nb, "without pictures")
