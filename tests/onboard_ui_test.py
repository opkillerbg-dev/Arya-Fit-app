#!/usr/bin/env python3
"""Real-browser test of the onboarding wizard shell (S4): screens 0-3, back, draft resume, skip defaults, units, Android back. Run from repo root."""
import json, subprocess, sys, time, os
from playwright.sync_api import sync_playwright
PORT = "8890"; root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "web")
srv = subprocess.Popen([sys.executable, "-m", "http.server", PORT], cwd=root, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
URL = f"http://localhost:{PORT}/index.html"; fails = []
def check(n, c, i=""):
    print(("ok   " if c else "FAIL ") + n + ("" if c else "  -> " + str(i)))
    if not c: fails.append(n)
def page(b, seed=None):
    ctx = b.new_context(viewport={"width": 390, "height": 844}); pg = ctx.new_page(); errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)[:160]))
    pg.goto(URL, wait_until="load"); pg.wait_for_timeout(800)
    if seed is not None:
        pg.evaluate("s=>{localStorage.clear();for(const k in s)localStorage.setItem(k,s[k])}", seed); pg.reload(wait_until="load")
    pg.wait_for_timeout(1500)
    return ctx, pg, errs
def txt(pg): return pg.evaluate("document.getElementById('ax-ob')?document.getElementById('ax-ob').innerText:''")
def draft(pg): return pg.evaluate("AxProfile.draftGet()")
try:
    with sync_playwright() as pw:
        try: b = pw.chromium.launch(channel="chrome")
        except Exception: b = pw.chromium.launch()
        ctx, pg, errs = page(b)
        check("automated browsers skip the autostart (so other UI tests are not blocked)", not pg.evaluate("AxOnboard.isOpen()") and pg.evaluate("AxOnboard.isFresh()"))
        pg.evaluate("AxOnboard.open()"); pg.wait_for_timeout(200)
        check("welcome screen opens full screen with Start and Skip", "Start" in txt(pg) and "Skip, use a standard plan" in txt(pg))
        pg.click("#ob-go"); pg.wait_for_timeout(200)
        check("screen 1 shows you-questions and a progress bar", "About you" in txt(pg) and pg.evaluate("!!document.querySelector('#ax-ob [role=progressbar]')"))
        pg.fill("#ob-name", "Arya"); pg.fill("#ob-ht", "178"); pg.fill("#ob-wt", "76")
        pg.click("#ax-ob .ob-c[data-v='30-39']"); pg.click("#ax-ob .ob-c[data-v='m']"); pg.wait_for_timeout(100)
        d = draft(pg)
        check("each answer is saved to the draft", d["name"] == "Arya" and d["ht"] == 178 and d["wt"] == 76 and d["age"] == "30-39" and d["sex"] == "m", d)
        pg.click("#ax-ob .ob-st[data-t='ob-wt'][data-s='1']"); pg.wait_for_timeout(100)
        check("stepper changes the value and the draft", draft(pg)["wt"] == 77, draft(pg))
        pg.click("#ax-ob .ob-c[data-v='imperial']"); pg.wait_for_timeout(200)
        check("switching to imperial converts what is shown (5 ft 10 in, 170 lb) and keeps metric stored",
              pg.input_value("#ob-ft") == "5" and pg.input_value("#ob-in") == "10" and pg.input_value("#ob-wt") == "170" and draft(pg)["ht"] == 178, [pg.input_value("#ob-ft"), pg.input_value("#ob-in"), pg.input_value("#ob-wt"), draft(pg)["ht"]])
        pg.fill("#ob-ft", "6"); pg.fill("#ob-in", "0"); pg.fill("#ob-wt", "200"); pg.wait_for_timeout(100)
        d = draft(pg)
        check("imperial entry is stored as metric (183 cm, 90.7 kg)", d["units"] == "imperial" and d["ht"] == 183 and abs(d["wt"] - 90.7) < 0.2, d)
        pg.click("#ax-ob .ob-c[data-v='under18']"); pg.wait_for_timeout(100)
        check("under 18 shows the gentle note", pg.evaluate("!document.getElementById('ob-u18').hidden"))
        pg.click("#ax-ob .ob-c[data-v='30-39']"); pg.click("#ob-next"); pg.wait_for_timeout(200)
        check("Next goes to the health screen", "health check" in txt(pg).lower())
        pg.click("#ax-ob .ob-c[data-v='notsure']"); pg.wait_for_timeout(100)
        check("Not sure shows the doctor note and stores gentle mode", pg.evaluate("!document.getElementById('ob-hn').hidden") and draft(pg)["health"] == "check")
        pg.click("#ax-ob .ob-c[data-v='no']"); pg.wait_for_timeout(100)
        check("No clears the note and stores ok", pg.evaluate("document.getElementById('ob-hn').hidden") and draft(pg)["health"] == "ok")
        pg.click("#ob-back"); pg.wait_for_timeout(200)
        check("Back returns to screen 1 with answers intact", "About you" in txt(pg) and pg.input_value("#ob-name") == "Arya")
        pg.click("#ob-next"); pg.click("#ob-next"); pg.wait_for_timeout(200)
        check("goal screen lists five goals", pg.evaluate("document.querySelectorAll('#ax-ob .ob-o').length") == 5)
        pg.click("#ax-ob .ob-o[data-v='muscle']"); pg.wait_for_timeout(200); pg.click("#ax-ob .ob-c[data-v='run']"); pg.wait_for_timeout(100)
        check("main goal plus one extra saved", draft(pg)["goal"] == {"main": "muscle", "extra": "run"}, draft(pg))
        pg.click("#ax-ob .ob-o[data-v='run']"); pg.wait_for_timeout(200)
        check("picking the extra as main clears the extra", draft(pg)["goal"] == {"main": "run", "extra": None}, draft(pg))
        # resume after a restart
        pg.reload(wait_until="load"); pg.wait_for_timeout(1500)
        pg.evaluate("AxOnboard.open()"); pg.wait_for_timeout(200)
        check("close and reopen resumes on the same screen with answers", pg.evaluate("AxOnboard.step()") == 3 and "main goal" in txt(pg).lower() and draft(pg)["name"] == "Arya")
        # Android back
        pg.evaluate("axBack()"); pg.wait_for_timeout(200)
        check("Android back steps back one screen", pg.evaluate("AxOnboard.step()") == 2)
        pg.evaluate("axBack();axBack();axBack()"); pg.wait_for_timeout(200)
        check("Android back on the welcome screen closes the wizard and keeps the draft", not pg.evaluate("AxOnboard.isOpen()") and draft(pg)["name"] == "Arya")
        check("a user who has logged any tick is not treated as fresh", not pg.evaluate("(()=>{const o=APP.plans[APP.active].st;o['1:wu']=1;const r=AxOnboard.isFresh();delete o['1:wu'];return r})()"))
        check("closing never created a profile or changed the plan", pg.evaluate("AxProfile.get()") is None)
        check("no page errors", not errs, errs); ctx.close()

        # skip defaults
        ctx, pg, errs = page(b)
        pg.evaluate("AxOnboard.open()"); pg.click("#ob-go"); pg.click("#ob-skip"); pg.wait_for_timeout(200)
        check("skipping 'about you' leaves everything empty and moves on", "health check" in txt(pg).lower() and draft(pg)["ht"] is None and draft(pg)["name"] == "")
        pg.click("#ob-skip"); pg.wait_for_timeout(200)
        check("skipping the health check is safe: gentle mode", draft(pg)["health"] == "check", draft(pg))
        pg.click("#ob-skip"); pg.wait_for_timeout(200)
        check("skipping the goal defaults to general fitness", draft(pg)["goal"]["main"] == "general", draft(pg))
        check("skipping screens 4-8 fills safe defaults", [pg.evaluate("AxOnboard.step()")][0] == 4 and True)
        for _ in range(5): pg.click("#ob-skip"); pg.wait_for_timeout(150)
        d = draft(pg)
        check("skip defaults: beginner, home, 3 days, 45 min, 8 weeks, today", d["xp"] == "beg" and d["env"] == "home" and d["days"] == 3 and d["mins"] == 45 and d["weeks"] == 8 and d["start"] == "today", d)
        check("skipped benchmarks stay empty (estimated later)", all(d["bench"][k] is None for k in ["push", "pull", "squat", "plank", "run"]), d["bench"])
        check("after the last question comes the review screen with Create and Change answers", "Your starting levels" in txt(pg) and pg.evaluate("!!document.getElementById('ob-create')&&!!document.getElementById('ob-change')"))
        check("review shows a 7-day strip and bars", pg.evaluate("document.querySelectorAll('#ax-ob .ob-d').length")==7 and pg.evaluate("document.querySelectorAll('#ax-ob .ob-bar').length")>=4)
        pg.click("#ob-change"); pg.wait_for_timeout(200)
        check("Change answers goes back to the first question screen with answers kept", pg.evaluate("AxOnboard.step()")==1 and "About you" in txt(pg))
        pg.evaluate("AxOnboard.close()"); pg.wait_for_timeout(200)
        check("close removes the overlay", not pg.evaluate("AxOnboard.isOpen()") and pg.evaluate("!document.getElementById('ax-ob')"))
        check("no page errors (skip path)", not errs, errs); ctx.close()

        # S5 flow
        ctx, pg, errs = page(b)
        pg.evaluate("AxOnboard.open()"); pg.click("#ob-go"); pg.click("#ob-skip"); pg.click("#ob-skip"); pg.click("#ax-ob .ob-o[data-v='muscle']"); pg.wait_for_timeout(150); pg.click("#ob-next"); pg.wait_for_timeout(150)
        check("screen 4 asks experience (3 options)", "How much have you trained" in txt(pg) and pg.evaluate("document.querySelectorAll('#ax-ob .ob-o').length") == 3)
        pg.click("#ax-ob .ob-o[data-v='int']"); pg.wait_for_timeout(150); pg.click("#ob-next"); pg.wait_for_timeout(150)
        check("screen 5 asks where; equipment list only for home with equipment", "Where will you train" in txt(pg) and "Pull-up bar" not in txt(pg))
        pg.click("#ax-ob .ob-o[data-v='homeplus']"); pg.wait_for_timeout(150)
        check("home with equipment shows 6 items, backpack pre-ticked", pg.evaluate("document.querySelectorAll('#ax-ob [data-m=equip] .ob-c').length") == 6 and draft(pg)["equip"] == ["backpack"], draft(pg)["equip"])
        pg.click("#ax-ob [data-m=equip] .ob-c[data-v='pullbar']"); pg.click("#ax-ob [data-m=equip] .ob-c[data-v='dumbbell']"); pg.wait_for_timeout(150)
        check("ticks are saved", set(draft(pg)["equip"]) == {"backpack", "pullbar", "dumbbell"}, draft(pg)["equip"])
        pg.click("#ob-next"); pg.wait_for_timeout(150)
        check("screen 6 has 5 benchmark cards and a lifts card (dumbbells)", pg.evaluate("document.querySelectorAll('#ax-ob .ob-card').length") == 6)
        pick = lambda k, i: pg.click(f"#ax-ob [data-b={k}] .ob-c[data-i='{i}']")
        pick("push", 5); pick("pull", 3); pick("squat", 3); pick("plank", 4); pick("run", -1); pg.wait_for_timeout(100)
        d = draft(pg)
        check("benchmarks saved as numbers, 'Not sure' as empty", d["bench"]["push"] == 50 and d["bench"]["pull"] == 3 and d["bench"]["squat"] == 30 and d["bench"]["plank"] == 90 and d["bench"]["run"] is None, d["bench"])
        pg.fill("#ob-l-squat", "80"); pg.wait_for_timeout(100)
        check("a lift weight is saved in kg", draft(pg)["bench"]["lifts"]["squat"] == 80, draft(pg)["bench"])
        pg.click("#ob-next"); pg.wait_for_timeout(150)
        t = txt(pg)
        check("screen 7 names pulling as the weak point with the numbers", "Pulling" in t and "3 pull-ups vs 50 push-ups" in t, t[:300])
        pg.click("#ax-ob [data-k=weakq] .ob-c[data-v='yes']"); pg.wait_for_timeout(150)
        check("Yes stores the weak point and that it was asked", draft(pg)["weak"][:1] == ["pull"] and draft(pg)["weakAsked"] is True, draft(pg)["weak"])
        pg.click("#ax-ob [data-k=weakq] .ob-c[data-v='no']"); pg.wait_for_timeout(150)
        check("No clears it", draft(pg)["weak"] == [] and draft(pg)["weakAsked"] is True)
        for v in ["pull", "push", "legs", "core", "run"]: pg.click(f"#ax-ob [data-m=want] .ob-c[data-v='{v}']"); pg.wait_for_timeout(60)
        check("want is capped at 4", len(draft(pg)["want"]) == 4, draft(pg)["want"])
        pg.click("#ax-ob [data-m=protect] .ob-c[data-v='knee']"); pg.click("#ax-ob [data-m=protect] .ob-c[data-v='shoulder']"); pg.wait_for_timeout(100)
        check("protect areas saved", set(draft(pg)["protect"]) == {"knee", "shoulder"}, draft(pg)["protect"])
        pg.click("#ax-ob [data-m=protect] .ob-c[data-v='none']"); pg.wait_for_timeout(100)
        check("None clears protect", draft(pg)["protect"] == [])
        pg.click("#ob-next"); pg.wait_for_timeout(150)
        check("screen 8 recommends 4 days for an intermediate", "Recommended for you: 4" in txt(pg) and pg.evaluate("!!document.querySelector('#ax-ob .ob-c.rec')"))
        pg.click("#ax-ob [data-k=days] .ob-c[data-v='5']"); pg.click("#ax-ob [data-k=mins] .ob-c[data-v='60']"); pg.click("#ax-ob [data-k=weeks] .ob-c[data-v='12']"); pg.click("#ax-ob [data-k=start] .ob-c[data-v='monday']"); pg.wait_for_timeout(100)
        d = draft(pg)
        check("schedule saved as numbers", d["days"] == 5 and d["mins"] == 60 and d["weeks"] == 12 and d["start"] == "monday", d)
        prof = pg.evaluate("AxProfile.clean(AxProfile.draftGet(),{draft:true})")
        check("the whole draft is a valid profile (clean keeps everything)", prof and prof["bench"]["pull"] == 3 and prof["goal"]["main"] == "muscle" and prof["xp"] == "int" and prof["env"] == "homeplus" and prof["days"] == 5, prof)
        plan = pg.evaluate("(()=>{const p=AxProfile.clean(AxProfile.draftGet(),{draft:true});const r=AxPlanGen.build(p,AxExDb,{now:Date.now()});return {w:r.gen.weak,n:Object.values(r.plan.days).filter(d=>d.type==='strength').length}})()")
        check("the engine builds a 5-day plan from the wizard answers; weak points come only from the wanted list (priority declined)", plan["n"] == 5 and set(plan["w"]) <= {"pull", "push", "legs", "core"} and len(plan["w"]) <= 2, plan)
        pg.click("#ob-next"); pg.wait_for_timeout(250)
        check("review: pulling is marked as the priority? (declined, so only wanted ones)", "Your starting levels" in txt(pg) and "Your week" in txt(pg))
        before = pg.evaluate("Object.keys(APP.plans)")
        planname = pg.evaluate("APP.plans[APP.active].plan.name")
        pg.click("#ob-create"); pg.wait_for_timeout(600)
        after = pg.evaluate("Object.keys(APP.plans)")
        check("Create adds a NEW plan and keeps the old one untouched", len(after) == len(before) + 1 and all(k in after for k in before) and pg.evaluate("APP.plans['default'].plan.name") == planname, [before, after])
        nid = [k for k in after if k not in before][0]
        check("the new plan is active, has 5 strength days and a gen link", pg.evaluate("APP.active") == nid and pg.evaluate("Object.values(APP.plans[APP.active].plan.days).filter(d=>d.type==='strength').length") == 5 and pg.evaluate("APP.plans[APP.active].gen.v") == 1)
        check("profile is done with levels, draft cleared, wizard closed", pg.evaluate("!!AxProfile.get()&&AxProfile.get().done&&AxProfile.get().levels.push>=0") and pg.evaluate("AxProfile.draftGet()") is None and not pg.evaluate("AxOnboard.isOpen()"))
        check("lands on Home", pg.evaluate("!document.getElementById('ax-v-home').hidden"))
        check("wizard never reopens for a person with a profile", not pg.evaluate("AxOnboard.isFresh()"))
        pk = pg.evaluate("JSON.parse(pack())")
        check("export keeps profile and gen; import cleaner accepts them", pk["profile"]["done"] is True and pk["plans"][nid]["gen"]["levels"]["push"] >= 0 and pg.evaluate("!!AxProfile.cleanGen(JSON.parse(pack()).plans['%s'].gen)" % nid))
        check("no page errors (S5/S6 flow)", not errs, errs); ctx.close()

        # autostart on a real fresh install (automation flag lifted), once
        ctx = b.new_context(viewport={"width": 390, "height": 844}); ctx.add_init_script("window.__AX_OB_AUTO=1"); pg = ctx.new_page(); errs = []
        pg.on("pageerror", lambda e: errs.append(str(e)[:160])); pg.goto(URL, wait_until="load"); pg.wait_for_timeout(3500)
        check("a fresh install opens the wizard by itself after the splash", pg.evaluate("AxOnboard.isOpen()") and "Let's make a plan" in txt(pg))
        pg.click("#ob-skipall"); pg.wait_for_timeout(200); pg.reload(wait_until="load"); pg.wait_for_timeout(3500)
        check("after 'Skip, use a standard plan' it does not come back", not pg.evaluate("AxOnboard.isOpen()"))
        check("no page errors (autostart)", not errs, errs); ctx.close()

        # a person with history never sees it
        ctx = b.new_context(viewport={"width": 390, "height": 844}); ctx.add_init_script("window.__AX_OB_AUTO=1"); pg = ctx.new_page()
        pg.goto(URL, wait_until="load"); pg.wait_for_timeout(1500)
        pg.evaluate("(()=>{APP.plans[APP.active].st['1:wu']=1;save()})()"); pg.reload(wait_until="load"); pg.wait_for_timeout(3500)
        check("existing users with logged ticks do not get the wizard", not pg.evaluate("AxOnboard.isOpen()"))
        ctx.close()

        # skip everything on the welcome screen
        ctx, pg, errs = page(b)
        pg.evaluate("AxOnboard.open()"); pg.click("#ob-skipall"); pg.wait_for_timeout(200)
        check("'Skip, use a standard plan' closes it and it is no longer fresh", not pg.evaluate("AxOnboard.isOpen()") and not pg.evaluate("AxOnboard.isFresh()"))
        check("no page errors (skip all)", not errs, errs); ctx.close()

        # layout sanity on a small phone: nothing wider than the screen, buttons big enough
        ctx = b.new_context(viewport={"width": 360, "height": 640}); pg = ctx.new_page(); pg.goto(URL, wait_until="load"); pg.wait_for_timeout(1500)
        pg.evaluate("AxOnboard.open()"); pg.click("#ob-go"); pg.wait_for_timeout(300)
        check("no sideways scroll on a 360 px wide phone", pg.evaluate("document.getElementById('ob-bd').scrollWidth<=document.getElementById('ob-bd').clientWidth+1"))
        small = pg.evaluate("[...document.querySelectorAll('#ax-ob button')].filter(b=>b.offsetParent&&b.getBoundingClientRect().height<47).length")
        check("every button is at least 48 px tall", small == 0, small)
        ctx.close(); b.close()
finally:
    srv.terminate()
print("FAILED: " + ", ".join(fails) if fails else "ALL OK"); sys.exit(1 if fails else 0)
